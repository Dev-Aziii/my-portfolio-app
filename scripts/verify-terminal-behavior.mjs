import assert from "node:assert/strict";
import { launchBrowser, baseUrl, command, openTerminal } from "./terminal-browser.mjs";

const browser = await launchBrowser();
const errors = [];
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, reducedMotion: "reduce" });
  page.on("pageerror", (error) => errors.push(error.message));
  await page.goto(`${baseUrl}projects/teza?review=1`, { waitUntil: "networkidle" });
  await page.getByRole("radio", { name: "Light theme" }).click();
  await page.getByRole("button", { name: "Terminal Mode", exact: true }).click();
  assert.equal(await page.locator("#terminal-console").isVisible(), false);
  await page.waitForFunction(() => document.activeElement?.tagName === "BUTTON" && document.activeElement?.textContent?.includes("Dashboard Mode"));
  assert.match(await page.evaluate(() => document.activeElement?.textContent ?? ""), /Dashboard Mode/);
  await openTerminal(page);
  const dock = await page.locator("#terminal-console").evaluate((element) => ({ position: getComputedStyle(element).position, bottom: element.getBoundingClientRect().bottom, height: innerHeight }));
  assert.equal(dock.position, "fixed");
  assert.ok(Math.abs(dock.bottom - dock.height) < 2);
  await page.getByRole("button", { name: "Close terminal" }).click();
  assert.equal(await page.getByRole("combobox", { name: "Terminal command" }).isVisible(), false);
  await openTerminal(page);
  assert.equal(await page.getByRole("combobox", { name: "Terminal command" }).isVisible(), true);
  assert.equal(new URL(page.url()).pathname, "/projects/teza");
  assert.equal(new URL(page.url()).search, "?review=1");
  assert.equal(await page.evaluate(() => localStorage.getItem("theme")), "light");
  assert.equal(await page.evaluate(() => localStorage.getItem("presentation-mode")), "terminal");
  await command(page, "pwd");
  assert.match(await page.locator("[data-terminal-output]").innerText(), /~\/portfolio\/projects\/teza/);
  await command(page, "cd /");
  await page.waitForURL((url) => url.pathname === "/");
  await command(page, "cd projects");
  await page.waitForURL((url) => url.pathname === "/projects");
  await command(page, "cd elecsys");
  await page.waitForURL((url) => url.pathname === "/projects/elecsys");
  await page.goBack();
  await command(page, "pwd");
  assert.match(await page.locator("[data-terminal-output]").innerText(), /~\/portfolio\/projects$/);
  await page.goForward();
  await command(page, "pwd");
  assert.match(await page.locator("[data-terminal-output]").innerText(), /~\/portfolio\/projects\/elecsys/);
  await command(page, "cd /missing");
  assert.equal(new URL(page.url()).pathname, "/projects/elecsys");
  await command(page, 'echo "<img src=x onerror=alert(1)>"');
  assert.match(await page.locator("[data-terminal-output]").innerText(), /<img src=x onerror=alert\(1\)>/);
  assert.equal(await page.locator("[data-terminal-output] img").count(), 0);
  await command(page, "open https://example.com/");
  assert.match(await page.locator("[data-terminal-output]").innerText(), /Unknown target/);
  const input = page.getByRole("combobox", { name: "Terminal command" });
  await input.fill("cd /projects/te");
  await page.getByRole("option", { name: /teza/ }).waitFor();
  await input.press("Tab");
  assert.equal(await input.inputValue(), "cd /projects/teza/");
  assert.equal(new URL(page.url()).pathname, "/projects/elecsys");
  await input.press("Enter");
  await page.waitForURL((url) => url.pathname === "/projects/teza");
  await input.fill("c");
  await input.press("ArrowDown");
  await input.press("Enter");
  assert.equal(await input.inputValue(), "cd");
  assert.equal(new URL(page.url()).pathname, "/projects/teza");
  await input.fill("open ");
  await input.press("ArrowUp");
  const selectedVisible = await page.getByRole("option", { selected: true }).evaluate((element) => {
    const option = element.getBoundingClientRect(), list = element.closest("[role=listbox]").getBoundingClientRect();
    return option.top >= list.top && option.bottom <= list.bottom;
  });
  assert.equal(selectedVisible, true);
  await input.fill("cd projects");
  await input.dispatchEvent("compositionstart");
  await input.press("Enter");
  assert.equal(new URL(page.url()).pathname, "/projects/teza");
  assert.equal(await input.inputValue(), "cd projects");
  await input.dispatchEvent("compositionend");
  if (await input.getAttribute("aria-expanded") === "true") await input.press("Escape");
  await input.fill("");
  await input.press("ArrowUp");
  assert.equal(await input.inputValue(), "cd /projects/teza/");
  await command(page, "history");
  assert.match(await page.locator("[data-terminal-output]").innerText(), /cd elecsys/);
  await command(page, "clear");
  assert.equal((await page.locator("[data-terminal-output]").innerText()).trim(), "");
  await command(page, "history");
  assert.match(await page.locator("[data-terminal-output]").innerText(), /cd elecsys/);
  await command(page, "exit");
  await page.getByRole("radio", { name: "Light theme" }).waitFor();
  await page.waitForFunction(() => document.activeElement?.classList.contains("presentation-toggle"));
  assert.equal(await page.getByRole("radio", { name: "Light theme" }).getAttribute("aria-checked"), "true");
  assert.equal(new URL(page.url()).pathname, "/projects/teza");
  await page.getByRole("button", { name: "Terminal Mode", exact: true }).click();
  await openTerminal(page);
  assert.match(await page.locator("[data-terminal-output]").innerText(), /cd elecsys/);
  await page.reload({ waitUntil: "networkidle" });
  assert.equal(await page.locator("#terminal-console").isVisible(), false);
  await openTerminal(page);
  await input.waitFor();
  assert.equal((await page.locator("[data-terminal-output]").innerText()).trim(), "");
  assert.equal(await page.evaluate(() => getComputedStyle(document.body).backgroundColor), "rgb(5, 5, 5)");
  await command(page, "cd /");
  const portrait = page.getByRole("button", { name: "Show profile photo" });
  await portrait.click();
  assert.equal(await page.locator("[data-profile-dissolve]").getAttribute("data-profile-dissolve-state"), "open");
  assert.equal(await page.locator("[data-profile-image]").evaluate((element) => getComputedStyle(element).filter), "grayscale(1)");
  await page.getByRole("button", { name: "Show ASCII portrait" }).click();
  await page.waitForFunction(() => document.querySelector("[data-profile-dissolve]")?.getAttribute("data-profile-dissolve-state") === "closed");
  assert.equal(await page.locator("[data-profile-dissolve]").getAttribute("data-profile-dissolve-state"), "closed");
  await command(page, "cd certifications");
  await page.getByRole("button", { name: "View certificate: IT Specialist in Cybersecurity", exact: true }).click();
  await page.getByRole("dialog").waitFor();
  assert.equal(await page.evaluate(() => document.activeElement?.closest("[role=dialog]") !== null), true);
  assert.equal(await page.locator(".certificate-modal iframe").evaluate((element) => getComputedStyle(element).filter), "grayscale(1)");
  await page.getByRole("button", { name: "Close certificate dialog" }).click();
  assert.match(await page.evaluate(() => document.activeElement?.getAttribute("aria-label") ?? ""), /View certificate/);
  await page.goto(`${baseUrl}missing`, { waitUntil: "networkidle" });
  assert.match(await page.locator("main").innerText(), /404/);
  await command(page, "cd /");
  assert.equal(new URL(page.url()).pathname, "/");

  const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
  await mobile.goto(baseUrl, { waitUntil: "networkidle" });
  await mobile.locator(".dashboard-mobile-bar").getByRole("button", { name: "Terminal Mode", exact: true }).click();
  await openTerminal(mobile);
  const mobileInput = mobile.getByRole("combobox", { name: "Terminal command" });
  await mobileInput.fill("cd pro");
  await mobile.getByRole("option", { name: /projects/ }).tap();
  assert.equal(await mobileInput.inputValue(), "cd projects/");
  await mobile.getByRole("button", { name: "Run command" }).tap();
  await mobile.waitForURL((url) => url.pathname === "/projects");
  assert.equal(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await mobile.evaluate(() => window.scrollTo(0, document.body.scrollHeight));
  assert.equal(await mobile.locator("#terminal-console").evaluate((element) => Math.abs(element.getBoundingClientRect().bottom - innerHeight) < 2), true);
  await mobile.setViewportSize({ width: 390, height: 500 });
  await mobileInput.focus();
  assert.equal(await mobileInput.evaluate((element) => element.getBoundingClientRect().bottom <= innerHeight), true);
  await mobile.setViewportSize({ width: 320, height: 400 });
  await mobile.getByRole("button", { name: "Close terminal" }).tap();
  await mobile.locator("#terminal-console").waitFor({ state: "hidden" });
  assert.equal(await mobile.locator("[data-terminal-launcher]").evaluate((element) => element.getBoundingClientRect().bottom <= innerHeight), true);
  await openTerminal(mobile);
  assert.equal(await mobileInput.evaluate((element) => element.getBoundingClientRect().bottom <= innerHeight), true);

  const animated = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  await animated.addInitScript(() => localStorage.setItem("presentation-mode", "terminal"));
  await animated.goto(baseUrl, { waitUntil: "networkidle" });
  await animated.getByRole("button", { name: "Show profile photo" }).click();
  await animated.waitForFunction(() => document.querySelector("[data-profile-dissolve]")?.getAttribute("data-profile-dissolve-state") === "revealing");
  await animated.getByRole("button", { name: "Show ASCII portrait" }).click();
  await animated.getByRole("button", { name: "Show profile photo" }).click();
  await animated.waitForFunction(() => document.querySelector("[data-profile-dissolve]")?.getAttribute("data-profile-dissolve-state") === "open");
  await animated.getByRole("button", { name: "Show ASCII portrait" }).click();
  await animated.emulateMedia({ reducedMotion: "reduce" });
  await animated.waitForFunction(() => document.querySelector("[data-profile-dissolve]")?.getAttribute("data-profile-dissolve-state") === "closed");
  const expectedAscii = await animated.evaluate(async () => (await import("/src/data/profileAscii.ts")).profileAscii);
  assert.equal(await animated.locator("[data-profile-ascii]").textContent(), expectedAscii);

  const blocked = await browser.newPage({ reducedMotion: "reduce" });
  await blocked.addInitScript(() => {
    Storage.prototype.getItem = () => { throw new Error("storage blocked"); };
    Storage.prototype.setItem = () => { throw new Error("storage blocked"); };
  });
  await blocked.goto(baseUrl, { waitUntil: "networkidle" });
  await blocked.getByRole("radio", { name: "Light theme" }).click();
  await blocked.getByRole("button", { name: "Terminal Mode", exact: true }).click();
  await command(blocked, "theme");
  assert.match(await blocked.locator("[data-terminal-output]").innerText(), /Dashboard theme: light/);
  await command(blocked, "exit");
  assert.equal(await blocked.getByRole("radio", { name: "Light theme" }).getAttribute("aria-checked"), "true");
  assert.deepEqual(errors, []);
  await import("./verify-terminal-refinements.mjs");
  await import("./verify-terminal-panel.mjs");
  console.log("Terminal behavior checks passed: switching, persistence, routes, commands, completion, history, portrait, certificates, mobile, compact console and blocked storage.");
} finally { await browser.close(); }
