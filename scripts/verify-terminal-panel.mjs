import assert from "node:assert/strict";
import { launchBrowser, baseUrl, command } from "./terminal-browser.mjs";

const browser = await launchBrowser();
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, reducedMotion: "reduce" });
  await page.addInitScript(() => localStorage.setItem("presentation-mode", "terminal"));
  await page.goto(baseUrl, { waitUntil: "networkidle" });
  const panel = page.locator("#terminal-console"), input = page.getByRole("combobox", { name: "Terminal command" });
  assert.equal(await panel.isVisible(), false, "panel starts fully closed");
  const pageHeight = await page.evaluate(() => document.body.scrollHeight);
  await page.getByRole("button", { name: "[ Open Terminal ]", exact: true }).click();
  await page.waitForFunction(() => document.activeElement?.getAttribute("aria-label") === "Terminal command");
  assert.equal(await page.evaluate(() => document.body.scrollHeight), pageHeight, "overlay does not resize page");
  assert.ok(await panel.evaluate((element) => { const rect = element.getBoundingClientRect(); return Math.abs(rect.left) < 1 && Math.abs(rect.right - innerWidth) < 1 && Math.abs(rect.bottom - innerHeight) < 1; }));
  assert.equal(await panel.evaluate((element) => element.parentElement === document.body), true, "panel is body-portaled");
  const handle = page.getByRole("separator", { name: "Resize terminal" });
  const expectHeight = (expected) => page.waitForFunction((value) => document.querySelector("#terminal-console").getBoundingClientRect().height === value, expected);
  const height = () => panel.evaluate((element) => element.getBoundingClientRect().height);
  await expectHeight(300);
  await handle.focus(); await handle.press("ArrowUp"); await expectHeight(324);
  await handle.press("Shift+ArrowDown"); await expectHeight(260);
  await handle.press("End");
  await page.waitForFunction(() => document.querySelector("#terminal-console").getBoundingClientRect().top >= document.querySelector(".terminal-header").getBoundingClientRect().bottom + 15);
  assert.ok(await panel.evaluate((element) => element.getBoundingClientRect().top >= document.querySelector(".terminal-header").getBoundingClientRect().bottom + 15));
  await handle.press("Home"); await expectHeight(160);
  await handle.dblclick(); await expectHeight(300);
  const box = await handle.boundingBox();
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
  await page.mouse.down(); await page.mouse.move(box.x + box.width / 2, box.y - 95, { steps: 5 });
  await page.waitForFunction(() => document.querySelector("#terminal-console").getBoundingClientRect().height > 390);
  assert.equal(await page.evaluate(() => document.body.style.userSelect), "none");
  await page.mouse.up(); assert.equal(await page.evaluate(() => document.body.style.userSelect), "");
  const preferred = await height();
  await input.fill("echo saved draft");
  await page.getByRole("button", { name: "Close terminal", exact: true }).click();
  assert.equal(await panel.isVisible(), false);
  assert.equal(await page.evaluate(() => document.activeElement?.hasAttribute("data-terminal-launcher")), true);
  await page.getByRole("button", { name: "[ Open Terminal ]", exact: true }).click();
  await input.waitFor(); assert.equal(await input.inputValue(), "echo saved draft"); await expectHeight(preferred);
  await input.press("Escape"); // no suggestions: close completely
  assert.equal(await panel.isVisible(), false);
  await page.getByRole("button", { name: "[ Open Terminal ]", exact: true }).click();
  await input.fill("c"); await page.getByRole("listbox").waitFor();
  await input.press("Escape"); assert.equal(await panel.isVisible(), true); assert.equal(await page.getByRole("listbox").count(), 0);
  await input.press("Escape"); assert.equal(await panel.isVisible(), false);
  await page.getByRole("button", { name: "[ Open Terminal ]", exact: true }).click();
  await input.fill("cd projects"); await input.press("Enter"); await page.waitForURL((url) => url.pathname === "/projects");
  assert.equal(await panel.isVisible(), true); await expectHeight(preferred);
  await page.goBack(); assert.equal(await panel.isVisible(), true);
  await page.getByRole("button", { name: "[ Dashboard Mode ]", exact: true }).click();
  await page.getByRole("button", { name: "Terminal Mode", exact: true }).click();
  assert.equal(await panel.isVisible(), false, "mode reentry starts closed");
  await page.getByRole("button", { name: "[ Open Terminal ]", exact: true }).click(); await expectHeight(preferred);
  await page.reload({ waitUntil: "networkidle" }); assert.equal(await panel.isVisible(), false);
  await page.getByRole("button", { name: "[ Open Terminal ]", exact: true }).click(); await expectHeight(300);
  // IME Escape cancels composition without closing the console.
  await input.dispatchEvent("compositionstart");
  await input.press("Escape");
  assert.equal(await panel.isVisible(), true);
  await input.dispatchEvent("compositionend");
  // New output does not move readers who have scrolled away from the prompt.
  await command(page, "help");
  await input.fill("echo retained scroll");
  const transcript = page.locator(".terminal-transcript");
  await transcript.evaluate((element) => { element.scrollTop = 0; });
  await page.waitForFunction(() => document.querySelector(".terminal-transcript").scrollTop === 0);
  await input.press("Enter");
  await page.waitForFunction(() => document.querySelector("[data-terminal-output]").textContent.includes("retained scroll"));
  assert.equal(await transcript.evaluate((element) => element.scrollTop), 0);
  await page.locator("[data-terminal-launcher]").evaluate((element) => element.click());
  assert.ok(await input.evaluate((element) => { const rect = element.getBoundingClientRect(), area = element.closest(".terminal-transcript").getBoundingClientRect(); return rect.top >= area.top && rect.bottom <= area.bottom; }), "focus launcher reveals prompt even if already focused");
  await handle.focus(); await handle.press("ArrowUp");
  // A cancelled touch/pen resize restores page selection and releases the capture.
  await handle.dispatchEvent("pointerdown", { pointerId: 15, isPrimary: true, pointerType: "pen", button: 0, clientY: 600 });
  await handle.dispatchEvent("pointerup", { pointerId: 99, isPrimary: false, pointerType: "touch" });
  assert.equal(await panel.getAttribute("data-resizing"), "true", "another pointer cannot stop the captured drag");
  await handle.dispatchEvent("pointercancel", { pointerId: 15, isPrimary: true, pointerType: "pen" });
  assert.equal(await page.evaluate(() => document.body.style.userSelect), "");
  assert.equal(await panel.getAttribute("data-resizing"), "false");
  await handle.dispatchEvent("pointerdown", { pointerId: 16, isPrimary: true, pointerType: "pen", button: 0, clientY: 600 });
  await page.evaluate(() => window.dispatchEvent(new Event("blur")));
  assert.equal(await page.evaluate(() => document.body.style.userSelect), "");
  await handle.dispatchEvent("pointerdown", { pointerId: 17, isPrimary: true, pointerType: "pen", button: 0, clientY: 600 });
  await page.getByRole("button", { name: "Close terminal", exact: true }).click();
  assert.equal(await page.evaluate(() => document.body.style.userSelect), "");
  // Real CDP touch gestures exercise capture and touch-action, rather than only synthetic events.
  const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, reducedMotion: "reduce" });
  await mobile.addInitScript(() => localStorage.setItem("presentation-mode", "terminal"));
  await mobile.goto(baseUrl, { waitUntil: "networkidle" });
  await mobile.getByRole("button", { name: "[ Open Terminal ]", exact: true }).tap();
  const touchBox = await mobile.getByRole("separator", { name: "Resize terminal" }).boundingBox();
  const cdp = await mobile.context().newCDPSession(mobile);
  await cdp.send("Input.dispatchTouchEvent", { type: "touchStart", touchPoints: [{ x: 190, y: touchBox.y + 4 }] });
  await cdp.send("Input.dispatchTouchEvent", { type: "touchMove", touchPoints: [{ x: 190, y: touchBox.y - 96 }] });
  await cdp.send("Input.dispatchTouchEvent", { type: "touchEnd", touchPoints: [] });
  await mobile.waitForFunction(() => document.querySelector("#terminal-console").getBoundingClientRect().height > 340);
  assert.equal(await mobile.evaluate(() => document.body.style.userSelect), "");
  assert.equal(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  const mobileHeight = await mobile.locator("#terminal-console").evaluate((element) => element.getBoundingClientRect().height);
  await mobile.getByRole("combobox").fill("open ");
  await mobile.getByRole("listbox").waitFor();
  await mobile.evaluate(() => {
    Object.defineProperty(visualViewport, "height", { configurable: true, value: 240 });
    Object.defineProperty(visualViewport, "offsetTop", { configurable: true, value: 40 });
    visualViewport.dispatchEvent(new Event("resize"));
  });
  await mobile.waitForFunction(() => {
    const rect = document.querySelector("#terminal-console").getBoundingClientRect();
    const header = document.querySelector(".terminal-header").getBoundingClientRect();
    const prompt = document.querySelector(".terminal-live-command input").getBoundingClientRect();
    return Math.abs(rect.bottom - 280) < 1 && rect.top >= header.bottom + 15 && prompt.bottom <= 280;
  });
  await mobile.evaluate(() => { delete visualViewport.height; delete visualViewport.offsetTop; visualViewport.dispatchEvent(new Event("resize")); });
  await mobile.waitForFunction((expected) => Math.abs(document.querySelector("#terminal-console").getBoundingClientRect().height - expected) < 1, mobileHeight);
  // Closing is immediately inert, remains animated for180ms, and rapid reversal is safe.
  const animated = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  await animated.addInitScript(() => localStorage.setItem("presentation-mode", "terminal"));
  await animated.goto(baseUrl, { waitUntil: "networkidle" });
  await animated.locator("[data-terminal-launcher]").click();
  await animated.waitForFunction(() => document.activeElement?.getAttribute("aria-label") === "Terminal command");
  assert.equal(await animated.locator("#terminal-console").evaluate((element) => element.getAnimations()[0].effect.getTiming().duration), 180);
  await animated.getByRole("button", { name: "Close terminal" }).evaluate((element) => element.click());
  assert.equal(await animated.locator("#terminal-console").evaluate((element) => element.inert), true);
  await animated.locator("[data-terminal-launcher]").click();
  await animated.waitForFunction(() => document.activeElement?.getAttribute("aria-label") === "Terminal command");
  await animated.emulateMedia({ reducedMotion: "reduce" });
  await animated.getByRole("button", { name: "Close terminal" }).click();
  await animated.locator("#terminal-console").waitFor({ state: "hidden" });
  console.log("Sliding panel checks passed: closed defaults, full width, overlay, focus, drag/touch/keyboard resize, cancellation, session, routes and reset.");
} finally { await browser.close(); }
